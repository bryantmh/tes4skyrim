def _zip(folder, name, files):
    """A finished-mod zip holding `files` ({path: bytes})."""
    folder.mkdir(parents=True, exist_ok=True)
    path = folder / f"{name}.zip"
    with zipfile.ZipFile(path, "w") as zf:
        for member, data in files.items():
            zf.writestr(member, data)
    return path


def _finished(tmp_path):
    """Three finished mods in an output folder: LOD, a game and the runtime."""
    folder = tmp_path / "output" / "Finished Mods"
    _zip(folder, "AutoConvertLOD", {"meshes/lod/a.nif": b"x"})
    _zip(folder, "Nehrim", {"Nehrim.esm": b"TES4", "textures/a.dds": b"x"})
    _zip(folder, "TESRuntime", {"SKSE/Plugins/TESRuntime.dll": b"MZ"})
    return tmp_path / "output"


def _portable_mo2(tmp_path):
    """A portable MO2 instance with one profile and a mod of the user's own."""
    root = tmp_path / "MO2"
    (root / "profiles" / "Default").mkdir(parents=True)
    (root / "mods" / "SkyUI").mkdir(parents=True)
    (root / "ModOrganizer.exe").write_bytes(b"MZ")
    (root / "ModOrganizer.ini").write_text(
        "[General]\ngameName=Skyrim Special Edition\nselected_profile=@ByteArray(Default)\n", encoding="utf-8")
    profile = root / "profiles" / "Default"
    (profile / "modlist.txt").write_text("# This file was automatically generated by Mod Organizer.\n+SkyUI\n",
                                         encoding="utf-8")
    (profile / "plugins.txt").write_text("*SkyUI_SE.esp\n", encoding="utf-8")
    return root


