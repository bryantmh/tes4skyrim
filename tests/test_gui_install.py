def test_vortex_downloads_copies_each_zip_once(tmp_path):
    """A copied zip reads as installed until it is rebuilt."""
    out = _finished(tmp_path)
    downloads = tmp_path / "downloads" / "skyrimse"
    zips = install.finished_zips(out)
    install.vortex_downloads(downloads, zips, lambda _line: None)
    assert sorted(p.name for p in downloads.iterdir()) == ["AutoConvertLOD.zip", "Nehrim.zip", "TESRuntime.zip"]
    assert all(install.download_status(downloads, z) == "installed" for z in zips)


def _log_record(seq, writes):
    """One LevelDB log record (a FULL chunk) holding a write batch of (key, value) pairs."""
    body = struct.pack("<QI", seq, len(writes))
    for key, value in writes:
        body += bytes([1, len(key)]) + key + bytes([len(value)]) + value
    return struct.pack("<IHB", 0, len(body), 1) + body


def test_staging_folder_reads_the_newest_write_and_fills_placeholders(tmp_path):
    """Vortex's staging setting: the later write wins, and {USERDATA}/{game} expand."""
    key = vortex_state.STAGING_KEY.format(game="skyrimse").encode("utf-8")
    state = tmp_path / "Vortex" / "state.v2"
    state.mkdir(parents=True)
    old = json.dumps(r"C:\Old\{game}").encode("utf-8")
    new = json.dumps(r"{USERDATA}\{game}\mods").encode("utf-8")
    (state / "000003.log").write_bytes(_log_record(10, [(key, old)]) + _log_record(11, [(key, new)]))
    assert vortex_state.staging_folder("skyrimse", state) == os.path.normpath(
        str(tmp_path / "Vortex" / "skyrimse" / "mods"))


def test_staging_folder_is_empty_without_vortex(tmp_path):
    """No state folder means no staging folder, not an error."""
    assert vortex_state.staging_folder("skyrimse", tmp_path / "missing") == ""


def _block(entries) -> bytes:
    """One uncompressed LevelDB table block (no shared key prefixes, one restart point)."""
    body = b"".join(bytes([0, len(k), len(v)]) + k + v for k, v in entries)
    return body + struct.pack("<II", 0, 1)


def _table(blocks) -> bytes:
    """An `.ldb` file of (separator user key, block bytes, compressed flag) blocks plus index and footer."""
    data, index = b"", []
    for sep, block, compressed in blocks:
        index.append((sep + b"\xff" * 8, bytes([len(data), len(block)])))
        data += block + bytes([1 if compressed else 0]) + b"\0" * 4
    index_block = _block(index)
    handles = bytes([0, 0, len(data), len(index_block)])
    data += index_block + b"\0" * 5
    return data + handles + b"\0" * (40 - len(handles)) + b"\x57\xfb\x80\x8b\x24\x75\x47\xdb"


def test_table_lookup_reads_only_the_block_that_can_hold_the_key(tmp_path):
    """Blocks before and after the key's range are never decompressed (here they would fail to)."""
    key = b"settings###downloads###path"
    tag = (5 << 8 | 1).to_bytes(8, "little")
    broken = b"\x7f\x00"
    state = tmp_path / "state.v2"
    state.mkdir()
    (state / "000005.ldb").write_bytes(_table([
        (b"a", broken, True),
        (b"t", _block([(key + tag, json.dumps(r"F:\Downloads").encode())]), False),
        (b"z", broken, True)]))
    assert vortex_state.read_setting(key.decode(), state) == r"F:\Downloads"


def test_snappy_copies_back_references():
    """A literal then a 1-byte-offset copy repeats it, as LevelDB blocks use."""
    data = bytes([8, 0b00001100]) + b"abcd" + bytes([0b00000001, 4])
    assert vortex_state.snappy(data) == b"abcdabcd"
