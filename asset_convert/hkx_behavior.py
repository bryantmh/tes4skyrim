# The engine-side graph interface: SSE's movement controller / combat / AI
# bind these by name at graph init (every vanilla creature behavior declares
# them — vanilla dogbehavior has 65 variables; this is the engine-set/read
# subset).  A graph with NO variables leaves the movement hookup dead: the
# actor plays its start state forever and never walks or reacts.
# Third field = initial word value.  Vanilla dogbehavior inits IsAttackReady
# and bEquipOK to 1 — the combat controller reads them before ever sending
# an attackStart_* event, so a 0 default means the actor follows its target
# but NEVER attacks (2026-07-09 no-attacks root cause, with the weaponDraw
# reply below).  iCombatStance is engine-written on stance changes and
# drives the StartCombat/StopCombat expression pair.
ENGINE_VARIABLES = [
    ('Speed', 'REAL', 0), ('Direction', 'REAL', 0), ('TurnDelta', 'REAL', 0),
    ('TurnDeltaDamped', 'REAL', 0), ('SpeedSampled', 'REAL', 0),
    ('staggerMagnitude', 'REAL', 0), ('staggerDirection', 'REAL', 0),
    ('iState', 'INT32', 0), ('iGetUpType', 'INT32', 0),
    ('iCharacterSelector', 'INT32', 0), ('iCombatStance', 'INT32', 0),
    # walk(0)/run(1) gait family — the forward locomotion SM's start state
    # (vanilla quadruped: `iMovementSpeed = cond((Speed < 100), 0, 1)`)
    ('iMovementSpeed', 'INT32', 0),
    ('IsAttacking', 'BOOL', 0), ('IsAttackReady', 'BOOL', 1),
    ('bEquipOK', 'BOOL', 1),
    # Weapon-class state the ENGINE writes when it equips something, and which
    # the equip state machine switches on. Vanilla weapon-using creature graphs
    # declare these (draugr/falmer) and bare-handed ones do not (wolf/chaurus);
    # ck-cmd's TES4 variable template lists them too (ConvertNif.cpp:6634-6638).
    # Without them the engine has no way to tell the graph WHICH draw animation
    # to play, so the weapon never leaves its sheath node.
    ('iRightHandType', 'INT32', 0), ('iLeftHandType', 'INT32', 0),
    ('iEquippedItemState', 'INT32', 0), ('IsUnequipping', 'BOOL', 0),
    ('IsRecoiling', 'BOOL', 0), ('IsStaggering', 'BOOL', 0),
    ('IsBleedingOut', 'BOOL', 0), ('IsBashing', 'BOOL', 0),
    ('bAnimationDriven', 'BOOL', 0), ('bAllowRotation', 'BOOL', 0),
    ('bHeadTracking', 'BOOL', 0), ('bCanHeadTrack', 'BOOL', 0),
    ('bDisableHeadTrack', 'BOOL', 0), ('bForceIdleStop', 'BOOL', 0),
]

# Magic interface, declared only for casters (vanilla splits the same way:
# atronach/chaurus declare these, wolf declares none). The engine WRITES
# bWantCastLeft/Right when the AI decides to cast and bM*h_Ready when the
# hand is armed, and READS IsCasting. All init to 0 — VERBATIM the vanilla
# atronach word values (a working caster), so readiness is the ENGINE's to
# grant, not ours to fake.
MAGIC_VARIABLES = [
    ('bWantCastRight', 'BOOL', 0), ('bWantCastLeft', 'BOOL', 0),
    ('bMRh_Ready', 'BOOL', 0), ('bMLh_Ready', 'BOOL', 0),
    ('IsCasting', 'BOOL', 0),
]

# Block interface, declared only when a guard clip exists (draugrbehavior
# vocabulary: the engine sends blockStart/Stop/HitStart/HitStop, writes
# iWantBlock, and reads IsBlocking — bound true inside the block states).
BLOCK_VARIABLES = [
    ('IsBlocking', 'BOOL', 0), ('iWantBlock', 'INT32', 0),
]


def movement_type_names(name: str, has_swim: bool = False) -> list:
    """The creature's engine movement-type names — the CONTRACT that makes an
    actor movable at all (2026-07-09, the tc-can't-move root cause).

    The engine registers an actor's movement types by enumerating the ROOT
    behavior graph's variables named `iState_<X>` and looking up the MOVT
    record whose MNAM == <X> (ck-cmd RetargetCreature.cpp does exactly this
    rename+MOVT-clone when retargeting creatures; vanilla dogbehavior
    declares iState_DogDefault/iState_DogRun matching MOVT MNAM DogDefault/
    DogRun). A graph with NO iState_* variables gives the movement
    controller ZERO movement types: the actor cannot move even under
    console `tc` control, no locomotion events are ever sent, and it idles
    forever — records, packages, clips and cache all being correct.

    These names are declared as INT32 graph variables here AND emitted as
    MOVT records by tes5_import/creature_races.py (via the manifest), so
    consistency is by construction, like the ATKE attack events.

    has_swim adds the water movement type: the graph's root expression
    switches iState onto it while the engine-written `isSwimming` is set
    (vanilla quadruped: `iState = cond((isSwimming ==1),
    iState_BearSwimDefault, iState_BearDefault)`), which is what gives the
    actor its swim speeds.

    NO movement type for casting.  A `<base>Rooted` all-zero MOVT selected by
    `iState = cond((IsCasting == 1), ...)` at the root was tried 2026-08-26
    and BROKE casting entirely in game — do not retry it.  Pinning a caster
    is done with bAnimationDriven in the cast chain's modifier list instead,
    which is what vanilla's own walking creature caster does (chaurus
    Casting_SpitAttack_MG → bAnimationDriven_IsActive, pointer-traced from
    chaurusbehavior.hkx; the chaurus declares only ChaurusDefault_MT).
    """
    base = f'TES4{name.lower()}'
    out = [f'{base}Default', f'{base}Run']
    if has_swim:
        out.append(f'{base}Swim')
    return out


def graph_variables(clips: dict, movement_types: list) -> list:
    """The graph's variable table, in declaration order: (name, type,
    initial word value).  Shared with tools/live/graph_vars.py, which reads
    a LIVE actor's hkbVariableValueSet back by this same order.

    iState family: vanilla-style movement-type tags (dogbehavior:
    iState_DogDefault=30/iState_DogRun=31, iState initialized to Default).
    """
    variables = [(n, t, iv) for n, t, iv in ENGINE_VARIABLES]
    if cast_phase_defs(clips):
        variables += MAGIC_VARIABLES
    if clips.get('block', {}).get('idle'):
        variables += BLOCK_VARIABLES
    if any(mt.endswith('Swim') for mt in movement_types):
        # engine-written while the actor is in deep water; drives the
        # iState movement-type switch (vanilla quadruped verbatim)
        variables.append(('isSwimming', 'BOOL', 0))
    variables += [(f'iState_{mt}', 'INT32', 30 + i)
                  for i, mt in enumerate(movement_types)]
    return variables


def build_behavior_xml(behavior_name: str, clips: dict,
                       hit_times: dict = None,
                       movement_types: list = None,
                       speeds: dict = None,
                       ragdoll: dict = None,
                       sound_events: list = None,
                       vocal_states: list = None) -> str:
    """The generated v1 state machine (see module docstring).

    hit_times: {state_name: [seconds]} — Oblivion 'Hit' text-key times for
    attack clips, emitted as preHitFrame/HitFrame triggers (the engine's
    attack-damage contract; without HitFrame an attack never deals damage).

    sound_events: the FULLY-QUALIFIED `SoundPlay.<SNDR EditorID>` names this
    creature's clips trigger. Every one must be declared in the graph's own
    event table or the annotation resolves to no event and is dropped — an
    animationdata trigger is dispatched by matching its text against this
    table, NOT by parsing the payload at play time. Vanilla does exactly this:
    chickenbehavior.hkx declares `SoundPlay.NPCChickenPeck` /
    `SoundPlay.NPCChickenScratch`, wolfbehavior.hkx declares
    `SoundPlay.NPCDogPantLPMSD` + `SoundStop.NPCDogPantLPMSD`, matching their
    animationdata triggers verbatim. The bare `SoundPlay` entry those graphs
    also carry is the inert leftover, not the mechanism.

    vocal_states: [(state_name, enter_event, anim_stem)] single-play vocal
    idle states (CSDT Idle/Aware slots), entered via the engine's idle
    system (ActionIdle/ActionIdleWarn IDLE records) and returning through
    returnToDefault. Each plays its OWN annotation-carrying copy of the
    idle animation so the sound fires once per entry, never per loop.

    movement_types: MOVT MNAM strings (movement_type_names()) declared as
    `iState_<X>` INT32 variables — the engine's movement-type registration
    contract; without them the actor cannot move at all.

    speeds: {'walk': u/s, 'run': u/s, ...} clip root-motion speeds — anchor
    weights for the MoveForward parametric walk/run blend (vanilla
    ForwardWalkBlend: children weighted by natural clip speed, blend
    parameter bound to SpeedSampled, flags=17 SYNC|PARAMETRIC).

    ragdoll: hkx_ragdoll.ragdoll_info() dict — enables the Fully Ragdoll
    death state (DeathAnimation/Ragdoll/RagdollInstant routing, a
    structural clone of the vanilla dogbehavior root SM state 4). Oblivion
    creatures have no death animations: death IS the ragdoll.
    """
    hit_times = hit_times or {}
    movement_types = movement_types or []
    speeds = speeds or {}
    # ---- event vocabulary: standard + per-attack ----
    events = ['moveStart', 'moveStop', 'moveForward', 'moveBackward',
              'turnLeft', 'turnRight', 'turnStop', 'swimStart', 'swimStop',
              'runStart', 'walkStart',
              'recoilStart', 'recoilStop', 'recoilLargeStart',
              'staggerStart', 'staggerStop',
              'combatStanceStart', 'combatStanceStop',
              'weaponDraw', 'weaponSheathe', 'weaponSwing',
              'attackStop', 'returnToDefault', 'deathStart', 'IdleStop',
              'DeathAnimation', 'Ragdoll', 'RagdollInstant', 'GetUpBegin',
              'AddRagdollToWorld', 'RemoveCharacterControllerFromWorld',
              'SoundPlay', 'preHitFrame', 'HitFrame',
              'FootFront', 'FootBack', 'FootLeft', 'FootRight']
    cast_defs = cast_phase_defs(clips)
    if cast_defs:
        # Magic handshake (vanilla atronachflamebehavior vocabulary; see
        # CAST_MODES for the full protocol). BeginCast* is the graph's
        # message TO the engine; Spell_FireForget_* / Spell_Release /
        # Spell_Stop are the engine's inbound events; the Out clip's
        # MLh_SpellFire_Event trigger is what actually fires the spell.
        events += ['BeginCastRight', 'BeginCastLeft',
                   'MRh_SpellFire_Event', 'MLh_SpellFire_Event',
                   'Spell_FireForget_LH', 'Spell_FireForget_RH',
                   'Spell_Concentration_LH', 'Magic_Pre_Out',
                   'Spell_Ready', 'Spell_Release', 'Spell_Stop',
                   'Spell_Interrupt', 'InterruptCast', 'Magic_Equip']
    if clips.get('block', {}).get('idle'):
        events += ['blockStart', 'blockStop', 'blockHitStart',
                   'blockHitStop']
    # Vocal idle enter-events (the IDLE records' ENAM strings)
    events += [evt for _s, evt, _a in (vocal_states or [])]
    # Qualified sound events: one table entry per distinct
    # `SoundPlay.<SNDR EditorID>` the clips actually fire (see docstring).
    events += [e for e in dict.fromkeys(sound_events or []) if e not in events]
    attack_events = build_attack_events(clips)
    events += attack_events
    # One enter-event per equip/unequip state (see EQUIP_STANCES); the root
    # wildcard routes weaponDraw/weaponSheathe to whichever matches the
    # engine-set iRightHandType.
    equip_events = []
    for stance in sorted(clips.get('equip', {})):
        equip_events.append(f'equipStart_{stance}')
        if clips['equip'][stance][1]:
            equip_events.append(f'unequipStart_{stance}')
    events += equip_events
    eid = {n: i for i, n in enumerate(events)}

    if not clips['idle']:
        raise ValueError('creature has no idle clip')

    pf = HkxPackfile(first_id=80)

    # blend effect: smooth 0.3s (vanilla locomotion default)
    fx_smooth = pf.add('hkbBlendingTransitionEffect')
    for obj, nm, dur, mode in ((fx_smooth, 'BlendSmooth', 0.3,
                                'SELF_TRANSITION_MODE_CONTINUE_IF_CYCLIC'),):
        obj.param('variableBindingSet', 'null')
        obj.param('userData', 0)
        obj.param('name', nm)
        obj.param('selfTransitionMode', mode)
        obj.param('eventMode', 'EVENT_MODE_DEFAULT')
        obj.param('duration', f'{dur:.6f}')
        obj.param('toGeneratorStartTimeFraction', '0.000000')
        obj.param('flags', 'FLAG_IGNORE_FROM_WORLD_FROM_MODEL')
        obj.param('endMode', 'END_MODE_NONE')
        obj.param('blendCurve', 'BLEND_CURVE_SMOOTH')

    # variable table is fixed up-front so bindings can reference indices.
    variables = graph_variables(clips, movement_types)
    has_swim_mt = any(mt.endswith('Swim') for mt in movement_types)
    var_values = [30 if n == 'iState' else iv for n, _t, iv in variables]
    vidx = {n: i for i, (n, _t, _iv) in enumerate(variables)}

    def _binding_set(pairs):
        """hkbVariableBindingSet from (memberPath, variable name) pairs."""
        b = pf.add('hkbVariableBindingSet')
        b.param_raw('bindings',
                    '\n'.join(_BINDING_TMPL.format(member=m,
                                                   var_index=vidx[v])
                              for m, v in pairs),
                    numelements=len(pairs))
        b.param('indexOfBindingToEnable', -1)
        return b

    def _clip(name, kf_path, looping, triggers_ref='null', rate=1.0,
              anim=None):
        # anim: override the animation FILE stem. Annotations live in the
        # file, so a state whose events differ from the kf's other states
        # (vocal idles) — or must have none (the ragdoll pose) — points at
        # its own copy instead of the shared one.
        clip = pf.add('hkbClipGenerator')
        clip.param('variableBindingSet', 'null')
        clip.param('userData', 0)
        clip.param('name', name)
        clip.param('animationName',
                   'Animations\\' + (anim or clip_state_name(kf_path))
                   + '.hkx')
        clip.param('triggers', triggers_ref)
        clip.param('cropStartAmountLocalTime', '0.000000')
        clip.param('cropEndAmountLocalTime', '0.000000')
        clip.param('startTime', '0.000000')
        clip.param('playbackSpeed', f'{rate:.6f}')
        clip.param('enforcedDuration', '0.000000')
        clip.param('userControlledTimeFraction', '0.000000')
        clip.param('animationBindingIndex', -1)
        clip.param('mode', 'MODE_LOOPING' if looping else 'MODE_SINGLE_PLAY')
        clip.param('flags', 0)
        return clip

    def _trans_array(items):
        """hkbStateMachineTransitionInfoArray from
        (event_id, to_state, flags) tuples."""
        arr = pf.add('hkbStateMachineTransitionInfoArray')
        arr.param_raw(
            'transitions',
            '\n'.join(_TRANSITION_TMPL.format(effect=fx_smooth.ref,
                                              event_id=e, to_state=st,
                                              flags=f)
                      for e, st, f in items),
            numelements=len(items))
        return arr

    def _events_array(names):
        arr = pf.add('hkbStateMachineEventPropertyArray')
        arr.param_raw('events', '\n'.join(
            '<hkobject>\n'
            f'\t<hkparam name="id">{eid[n]}</hkparam>\n'
            '\t<hkparam name="payload">null</hkparam>\n'
            '</hkobject>' for n in names), numelements=len(names))
        return arr

    def _state(state_id, name, generator_ref, transitions=None,
               exit_events=None, enter_events=None):
        # referenced objects must be added BEFORE the stateInfo (hkxcmd's
        # parser rejects forward references)
        trans_ref = _trans_array(transitions).ref if transitions else 'null'
        enter_ref = (_events_array(enter_events).ref if enter_events
                     else 'null')
        exit_ref = _events_array(exit_events).ref if exit_events else 'null'
        st = pf.add('hkbStateMachineStateInfo')
        st.param('variableBindingSet', 'null')
        st.param_array('listeners', [])
        st.param('enterNotifyEvents', enter_ref)
        st.param('exitNotifyEvents', exit_ref)
        st.param('transitions', trans_ref)
        st.param('generator', generator_ref)
        st.param('name', name)
        st.param('stateId', state_id)
        st.param('probability', '1.000000')
        st.param('enable', True)
        return st

    def _make_sm(name, states, start_id=0, wildcard_ref='null',
                 binding_ref='null'):
        m = pf.add('hkbStateMachine')
        m.param('variableBindingSet', binding_ref)
        m.param('userData', 0)
        m.param('name', name)
        m.param_raw('eventToSendWhenStateOrTransitionChanges', (
            '<hkobject>\n\t<hkparam name="id">-1</hkparam>\n'
            '\t<hkparam name="payload">null</hkparam>\n</hkobject>'))
        m.param('startStateChooser', 'null')
        m.param('startStateId', start_id)
        m.param('returnToPreviousStateEventId', -1)
        m.param('randomTransitionEventId', -1)
        m.param('transitionToNextHigherStateEventId', -1)
        m.param('transitionToNextLowerStateEventId', -1)
        m.param('syncVariableIndex', -1)
        m.param('wrapAroundStateId', False)
        m.param('maxSimultaneousTransitions', 32)
        m.param('startStateMode', 'START_STATE_MODE_DEFAULT')
        m.param('selfTransitionMode', 'SELF_TRANSITION_MODE_NO_TRANSITION')
        m.param_array('states', [s.ref for s in states])
        m.param('wildcardTransitions', wildcard_ref)
        return m

    def _parametric_blend(name, plan):
        """Vanilla-style SYNC|PARAMETRIC speed blend: children are the same
        clips at scaled playbackSpeeds, each anchored (weight) at its true
        animation speed, blendParameter driven by SpeedSampled."""
        children = []
        for cnm, kf, rate, anchor in plan:
            child_clip = _clip(cnm, kf, True, rate=rate)
            ch = pf.add('hkbBlenderGeneratorChild')
            ch.param('variableBindingSet', 'null')
            ch.param('generator', child_clip.ref)
            ch.param('boneWeights', 'null')
            ch.param('weight', f'{anchor:.6f}')
            ch.param('worldFromModelWeight', '1.000000')
            children.append(ch)
        bind = _binding_set([('blendParameter', 'SpeedSampled')])
        blender = pf.add('hkbBlenderGenerator')
        blender.param('variableBindingSet', bind.ref)
        blender.param('userData', 0)
        blender.param('name', name)
        blender.param('referencePoseWeightThreshold', '0.000000')
        blender.param('blendParameter', '1.000000')
        blender.param('minCyclicBlendParameter', '0.000000')
        blender.param('maxCyclicBlendParameter', '1.000000')
        blender.param('indexOfSyncMasterChild', -1)
        blender.param('flags', 17)
        blender.param('subtractLastChild', False)
        blender.param_array('children', [c.ref for c in children])
        return blender

    def _direction_blend(name, children, flags=49):
        """SYNC|PARAMETRIC|CYCLIC blend on the engine-written `Direction`:
        vanilla chaurus `DirectionalBlend` / draugr `MT_Direction_Blend`
        verbatim (flags 49, min 0 / max 1, blendParameter bound to
        Direction; the swimming fish drops SYNC = 48).  Anchors: 0.0
        forward, 0.25 right, 0.5 backward, 0.75 left; CYCLIC wraps 1.0 back
        onto forward (no vanilla graph has a child at 1.0).

        EVERY CHILD IS A SPEED BLENDER, never a state machine: all eight
        draugr children and all four chaurus children are SpeedSampled
        blends (chaurus RightBlend = RightSlow@5 / Right@87.5 /
        Right_Run@350).  That is what keeps a strafe's leg rate matched to
        the actor's real speed -- with a bare strafe clip beside the
        forward SPEED blend, a 32 u/s sideways walk read as a 5 u/s creep on
        the forward child and the scamp "floated with its legs barely
        moving" (in game 2026-08-26).  children: [(generator ref, anchor)].
        """
        kids = []
        for gen_ref, anchor in children:
            ch = pf.add('hkbBlenderGeneratorChild')
            ch.param('variableBindingSet', 'null')
            ch.param('generator', gen_ref)
            ch.param('boneWeights', 'null')
            ch.param('weight', f'{anchor:.6f}')
            ch.param('worldFromModelWeight', '1.000000')
            kids.append(ch)
        bind = _binding_set([('blendParameter', 'Direction')])
        blender = pf.add('hkbBlenderGenerator')
        blender.param('variableBindingSet', bind.ref)
        blender.param('userData', 0)
        blender.param('name', name)
        blender.param('referencePoseWeightThreshold', '0.000000')
        blender.param('blendParameter', '0.000000')
        blender.param('minCyclicBlendParameter', '0.000000')
        blender.param('maxCyclicBlendParameter', '1.000000')
        blender.param('indexOfSyncMasterChild', -1)
        blender.param('flags', flags)
        blender.param('subtractLastChild', False)
        blender.param_array('children', [c.ref for c in kids])
        return blender

    def _gait_speed_blend(nm, kf, spd):
        """slow-creep@5 + clip@natural + clip@2x SpeedSampled blend for one
        gait clip (the chaurus per-direction layout, RightSlow / Right /
        Right_Run); a bare clip when the clip has no measurable root-motion
        speed.

        The 2x child is the same clip at playbackSpeed 2.0 (vanilla sabrecat
        ForwardRunBlend: RunSlow@0.75 / Run@1.15, one clip at two rates).
        It exists because the engine's commanded speed at a strafe heading
        is a blend of the MOVT columns, not the strafe column alone: live
        readback of a circling scamp (2026-08-26) showed Direction
        0.72-0.75 with Speed 33-53 u/s against a 31.8 u/s strafe clip, so
        the legs ran at 31.8 while the ground moved at 45 -- "slides to
        the side".  With SYNC|PARAMETRIC the rate interpolates between the
        anchors, so the feet keep pace up to twice the clip's own speed.
        Oblivion ships no run-strafe clip (the chaurus has Right_Run), so
        rate-scaling the walk strafe is the only source of a faster gait."""
        if not spd:
            return _clip(nm, kf, True)
        return _parametric_blend(
            f'{nm}Blend',
            [(f'{nm}Slow', kf, max(0.02, round(5.0 / spd, 3)), 5.0),
             (nm, kf, 1.0, spd),
             (f'{nm}Fast', kf, 2.0, round(spd * 2.0, 3))])

    def _direction_family(prefix, fwd_ref):
        """The Direction blend around ONE gait family (walk or run):
        forward @0 plus whatever strafe/backward clips the creature ships,
        each as its own speed blend.  None when there is nothing to blend
        (no strafe clips) -- the family then stays a plain forward gait."""
        loco_ = clips['locomotion']
        kids = [(fwd_ref, 0.0)]
        if 'StrafeRight' in loco_:
            kids.append((_gait_speed_blend(
                f'{prefix}StrafeRight', loco_['StrafeRight'],
                speeds.get('right')).ref, 0.25))
        if 'MoveBackward' in loco_ and ('StrafeRight' in loco_
                                        or 'StrafeLeft' in loco_):
            kids.append((_gait_speed_blend(
                f'{prefix}BackwardDir', loco_['MoveBackward'],
                speeds.get('back')).ref, 0.5))
        if 'StrafeLeft' in loco_:
            kids.append((_gait_speed_blend(
                f'{prefix}StrafeLeft', loco_['StrafeLeft'],
                speeds.get('left')).ref, 0.75))
        if len(kids) == 1:
            return None
        return _direction_blend(f'{prefix}DirectionalBlend', kids)

    # =====================================================================
    # Nested state machines (the vanilla quadruped topology, 2026-07-16).
    # The old FLAT graph made every engine event a root wildcard: combat
    # facing-adjustments (turnLeft/turnRight, sent continuously) hijacked
    # the whole graph — visible as constant left/right body-whipping — and
    # aborted every attack mid-swing (the "never attacks" report).  Vanilla
    # nests turns inside the Standing machine (unreachable while moving or
    # attacking) and enters attacks only via LOCAL transitions from
    # DefaultState.
    # =====================================================================
    loco = clips['locomotion']

    # ---- LocomotionBehavior: Forward(0) <-> Backward(1) ----
    loco_sm = None
    gait_eem = None
    if 'MoveForward' in loco:
        fplan = speed_blend_plan(clips, speeds)
        walk_gen = (_parametric_blend('ForwardWalkBlend', fplan) if fplan
                    else _clip('MoveForward', loco['MoveForward'], True))
        # Direction blend per gait FAMILY (walk / run), each child a speed
        # blend -- vanilla draugr keeps its walk and run families apart and
        # wraps each in its own flags-49 direction blend; a state machine
        # is never a direction-blend child (see _direction_blend).
        walk_gen = _direction_family('Walk', walk_gen.ref) or walk_gen
        rplan = run_blend_plan(clips, speeds)
        if rplan:
            # Two gait FAMILIES in two states (vanilla forwardlocomotion
            # layout): the walk blend and the run blend never mix clips;
            # runStart/walkStart switch between them on SpeedSampled with
            # hysteresis, and iMovementSpeed picks the start state.
            run_gen = _parametric_blend('ForwardRunBlend', rplan)
            run_gen = _direction_family('Run', run_gen.ref) or run_gen
            lo, hi = gait_thresholds(speeds)
            fwd_sm = _make_sm(
                'ForwardLocomotionBehavior',
                [_state(0, 'ForwardWalkState', walk_gen.ref,
                        transitions=[(eid['runStart'], 1, _F_LOCAL)]),
                 _state(1, 'ForwardRunState', run_gen.ref,
                        transitions=[(eid['walkStart'], 0, _F_LOCAL)])],
                binding_ref=_binding_set(
                    [('startStateId', 'iMovementSpeed')]).ref)
            fwd_gen = fwd_sm
            arr = pf.add('hkbExpressionDataArray')
            # comparison operators must be XML-escaped in the packfile text
            # (vanilla: `iMovementSpeed = cond((Speed &lt; 100), 0, 1)`)
            exprs = [('iMovementSpeed = cond((Speed &lt; 100), 0, 1)',
                      'EVENT_MODE_SEND_ONCE'),
                     (f'runStart if (SpeedSampled &gt; {hi})',
                      'EVENT_MODE_SEND_ON_FALSE_TO_TRUE'),
                     (f'walkStart if (SpeedSampled &lt; {lo})',
                      'EVENT_MODE_SEND_ON_FALSE_TO_TRUE')]
            arr.param_raw('expressionsData', '\n'.join(
                '<hkobject>\n'
                f'\t<hkparam name="expression">{e}</hkparam>\n'
                '\t<hkparam name="assignmentVariableIndex">-1</hkparam>\n'
                '\t<hkparam name="assignmentEventIndex">-1</hkparam>\n'
                f'\t<hkparam name="eventMode">{mode}</hkparam>\n'
                '</hkobject>' for e, mode in exprs), numelements=len(exprs))
            gait_eem = pf.add('hkbEvaluateExpressionModifier')
            gait_eem.param('variableBindingSet', 'null')
            gait_eem.param('userData', 2)
            gait_eem.param('name', 'ForwardLocomotion_EEM')
            gait_eem.param('enable', True)
            gait_eem.param('expressions', arr.ref)
        else:
            fwd_gen = walk_gen
        has_back = 'MoveBackward' in loco
        # Strafes live inside the gait families' Direction blends above
        # (see LOCOMOTION_STATES for why they cannot be event-entered
        # states).  The engine writes Direction every frame: 0 = forward,
        # 0.25 = right, 0.5 = backward, 0.75 = left; the engine's
        # moveBackward event still owns the dedicated
        # BackwardLocomotionState below.
        fwd_state = _state(
            0, 'ForwardLocomotionState', fwd_gen.ref,
            transitions=([(eid['moveBackward'], 1, _F_LOCAL)]
                         if has_back else None))
        loco_states = [fwd_state]
        if has_back:
            bplan = backward_blend_plan(clips, speeds)
            back_gen = (_parametric_blend('BackwardSpeedBlend', bplan)
                        if bplan
                        else _clip('MoveBackward', loco['MoveBackward'],
                                   True))
            loco_states.append(_state(
                1, 'BackwardLocomotionState', back_gen.ref,
                transitions=[(eid['moveForward'], 0, _F_LOCAL)]))
        loco_sm = _make_sm('LocomotionBehavior', loco_states)

    # ---- StandingIdleBehavior: NonCombatIdle(0) <-> CombatIdle(1) ----
    idle_clip = _clip('Idle', clips['idle'], True)
    combat_clip = _clip('CombatStance', combat_idle_clip(clips), True)
    standing_idle_sm = _make_sm('StandingIdleBehavior', [
        _state(0, 'NonCombatIdleState', idle_clip.ref,
               transitions=[(eid['combatStanceStart'], 1, _F_LOCAL)]),
        _state(1, 'CombatIdleState', combat_clip.ref,
               transitions=[(eid['combatStanceStop'], 0, _F_LOCAL)]),
    ])

    # ---- StandingBehavior: idle switch + looping turn-in-place states ----
    has_tr = 'TurnRight' in loco
    has_tl = 'TurnLeft' in loco
    idle_trans = []
    if has_tr:
        idle_trans.append((eid['turnRight'], 1, _F_LOCAL))
    if has_tl:
        idle_trans.append((eid['turnLeft'], 2, _F_LOCAL))
    standing_states = [_state(0, 'StandingIdleState', standing_idle_sm.ref,
                              transitions=idle_trans or None)]
    if has_tr:
        tr_trans = [(eid['turnStop'], 0, _F_LOCAL)]
        if has_tl:
            tr_trans.insert(0, (eid['turnLeft'], 2, _F_LOCAL))
        standing_states.append(_state(
            1, 'LoopingTurnRight',
            _clip('TurnRight', loco['TurnRight'], True).ref,
            transitions=tr_trans))
    if has_tl:
        tl_trans = [(eid['turnStop'], 0, _F_LOCAL)]
        if has_tr:
            tl_trans.insert(0, (eid['turnRight'], 1, _F_LOCAL))
        standing_states.append(_state(
            2, 'LoopingTurnLeft',
            _clip('TurnLeft', loco['TurnLeft'], True).ref,
            transitions=tl_trans))
    standing_sm = _make_sm('StandingBehavior', standing_states)

    # ---- DefaultBehavior: Standing(0) <-> Locomotion(1) ----
    default_states = [_state(
        0, 'StandingState', standing_sm.ref,
        transitions=([(eid['moveStart'], 1, _F_LOCAL)] if loco_sm else None))]
    if loco_sm:
        default_states.append(_state(
            1, 'LocomotionState', loco_sm.ref,
            transitions=[(eid['moveStop'], 0, _F_LOCAL)]))
    default_sm = _make_sm('DefaultBehavior', default_states)

    # ---- root state machine: DefaultState + single-play interrupts ----
    # Attack states wrap their clip in the vanilla IsActive modifier: while
    # the state is active it drives IsAttacking=1 (the combat controller's
    # in-progress flag), bAllowRotation=1 (target tracking during the
    # swing), bDisableHeadTrack=1.  Without IsAttacking the engine keeps
    # steering mid-swing.
    attack_isactive_bind = _binding_set([
        ('bIsActive0', 'IsAttacking'),
        ('bIsActive1', 'bAllowRotation'),
        ('bIsActive2', 'bDisableHeadTrack')])
    attack_isactive = pf.add('BSIsActiveModifier')
    attack_isactive.param('variableBindingSet', attack_isactive_bind.ref)
    attack_isactive.param('userData', 2)
    attack_isactive.param('name', 'BSIsActiveModifier_IsAttacking')
    attack_isactive.param('enable', True)
    for i in range(5):
        attack_isactive.param(f'bIsActive{i}', False)
        attack_isactive.param(f'bInvertActive{i}', False)
    attack_ml = pf.add('hkbModifierList')
    attack_ml.param('variableBindingSet', 'null')
    attack_ml.param('userData', 1)
    attack_ml.param('name', 'AttackModifierList')
    attack_ml.param('enable', True)
    attack_ml.param_array('modifiers', [attack_isactive.ref])

    def _clip_triggers(st_name, end_evt):
        items = []
        for t in hit_times.get(st_name, []):
            items.append(_TRIGGER_TMPL.format(
                time=max(0.0, t - 0.3), event_id=eid['weaponSwing'],
                rel='false'))
            items.append(_TRIGGER_TMPL.format(
                time=max(0.0, t - 0.1), event_id=eid['preHitFrame'],
                rel='false'))
            items.append(_TRIGGER_TMPL.format(
                time=t, event_id=eid['HitFrame'], rel='false'))
        if end_evt:
            items.append(_TRIGGER_TMPL.format(
                time=0.0, event_id=eid[end_evt], rel='true'))
        if not items:
            return 'null'
        trig = pf.add('hkbClipTriggerArray')
        trig.param_raw('triggers', '\n'.join(items), numelements=len(items))
        return trig.ref

    root_states_inner = []
    next_id = 1
    default_trans = []      # attackStart_* -> attack states (LOCAL)
    root_wilds = []

    for st, (_names, enter, stop_evt) in SINGLE_PLAY.items():
        if st not in clips['single']:
            continue
        end_evt = 'returnToDefault' if st != 'Death' else None
        clip = _clip(st, clips['single'][st], False,
                     _clip_triggers(st, end_evt))
        # A RAGDOLL-LESS creature (ghost, wraith, spectre: no bhk bodies in
        # the source skeleton, so hkx_ragdoll extracts nothing) never reaches
        # the AnimateToRagdoll / Fully Ragdoll wrapper below, and its Death
        # clip has no end trigger -- so the state holds the clip's LAST frame
        # forever.  For those creatures the last frame is NOT a corpse on the
        # ground: Oblivion's ghost death.kf keeps `Bip01 NonAccum` at
        # standing height (Z 65.0 -> 66.0 over the whole 1.17s clip) because
        # the body is meant to be HIDDEN by the NiVisController / morph /
        # alpha channels that a Havok clip cannot carry.  With the body still
        # shown and the character controller still under it, the corpse
        # hovers upright at head height -- the reported bug.
        #
        # Vanilla's ragdoll-less creature is the WITCHLIGHT: its skeleton
        # has one bhkRigidBody and ZERO constraints, its behavior graph
        # contains the string 'ragdoll' zero times, it has NO Death state
        # at all, and its `WitchlightRagdollInstant` IDLE deliberately
        # carries NO ENAM (the wisp's carries `RagdollInstant`) -- so no
        # death event ever reaches its graph and the engine disposes of
        # the actor itself.  Note what vanilla does NOT do: it never sends
        # RemoveCharacterControllerFromWorld (the string is absent from
        # witchlightbehavior.hkx entirely).  Dropping the controller with
        # no ragdoll to take over is the documented cause of corpses
        # falling through the floor, so we must not add it either.
        #
        # We keep the death ANIMATION -- Oblivion's ghosts have a real,
        # authored one the witchlight simply lacks -- and the visibility
        # channels recovered by kf_decode make it end on a hidden body
        # plus a visible ectoplasm puddle rather than an upright corpse.
        # The state itself stays exactly as vanilla builds a single-play
        # state: no enter notify, no exit notify, no end trigger.
        root_states_inner.append(_state(
            next_id, f'{st}State', clip.ref,
            exit_events=[stop_evt] if stop_evt else None))
        root_wilds.append((eid[enter], next_id, _F_WILD if st != 'Death'
                           else _F_GLOBAL))
        if st == 'Recoil':
            root_wilds.append((eid['recoilLargeStart'], next_id, _F_WILD))
        next_id += 1

    # ---- swimming (engine swimStart/swimStop; see SWIM_CLIPS) ----
    # A sub-machine mirroring the land standing/locomotion split, driven by
    # the same engine locomotion events. Vanilla sabrecat ships a single
    # looping SwimForward; the richer Oblivion gait sets (slaughterfish:
    # idle/turns/fast) wire in when authored.
    sw = clips.get('swim', {})
    if sw.get('forward'):
        swim_idle_kf = sw.get('idle') or sw['forward']
        sw_states = []
        idle_trans = [(eid['moveStart'], 1, _F_LOCAL)]
        if sw.get('left'):
            idle_trans.append((eid['turnLeft'], 3, _F_LOCAL))
        if sw.get('right'):
            idle_trans.append((eid['turnRight'], 4, _F_LOCAL))
        sw_states.append(_state(
            0, 'SwimIdleState',
            _clip('SwimIdle', swim_idle_kf, True).ref,
            transitions=idle_trans))
        splan = swim_blend_plan(clips, speeds)
        smove_gen = (_parametric_blend('SwimSpeedBlend', splan) if splan
                     else _clip('SwimMove', sw['forward'], True))
        move_trans = [(eid['moveStop'], 0, _F_LOCAL)]
        if sw.get('backward'):
            move_trans.append((eid['moveBackward'], 2, _F_LOCAL))
        sw_states.append(_state(1, 'SwimMoveState', smove_gen.ref,
                                transitions=move_trans))
        if sw.get('backward'):
            sw_states.append(_state(
                2, 'SwimBackState',
                _clip('SwimBack', sw['backward'], True).ref,
                transitions=[(eid['moveForward'], 1, _F_LOCAL),
                             (eid['moveStop'], 0, _F_LOCAL)]))
        for sid, role, st_name in ((3, 'left', 'SwimTurnLeft'),
                                   (4, 'right', 'SwimTurnRight')):
            if sw.get(role):
                sw_states.append(_state(
                    sid, f'{st_name}State',
                    _clip(st_name, sw[role], True).ref,
                    transitions=[(eid['turnStop'], 0, _F_LOCAL)]))
        swim_sm = _make_sm('SwimBehavior', sw_states)
        root_states_inner.append(_state(
            next_id, 'SwimState', swim_sm.ref,
            transitions=[(eid['swimStop'], 0, _F_LOCAL)]))
        root_wilds.append((eid['swimStart'], next_id, _F_WILD))
        next_id += 1

    # Attacks, gated by weapon stance.
    #
    # Oblivion ships one clip per weapon class under the SAME AnimGroup and
    # the engine picks by what is equipped: minotaur handtohandattackleft and
    # twohandattackleft BOTH declare AnimGroup 'AttackLeft'.  A flat graph
    # that transitions straight off the engine's attackStart_* event cannot
    # honour that, so an armed minotaur could play a bare-handed swing -- and
    # the H2H clips park the animated `Weapon` node ~70 units off the hand,
    # dragging the held warhammer out of its grip as they play.
    #
    # Vanilla gates this with NESTING, not conditions: draugrbehavior holds a
    # parent state per stance (H2H_Readied_State / 1HM_Sword_Readied_State /
    # 2HM_Readied_State / Bow_Readied_State) and each stance's *_Attack_State
    # children live INSIDE it.  A child state is only reachable while its
    # parent is the active state, so an H2H attack simply cannot be entered
    # while the actor is in the 2HM branch.  Which parent is active is chosen
    # by binding the wrapper machine's startStateId to the engine-written
    # weapon-class variable.
    #
    # NOT usable here, both verified the hard way:
    #   * hkbExpressionCondition on the transition -- hkxcmd cannot serialize
    #     the class; it drops the objects and leaves dangling pointers.
    #   * `EVENT if ((otherEvent) && (iRightHandType == n))` -- an expression
    #     can only read VARIABLES, never event names, so the guard is always
    #     false and NOTHING fires.  This file already documents that trap for
    #     the cast chain (see CAST_MODES); the equip dispatch below inherits
    #     it and is dead for the same reason.
    stance_of = clips.get('attack_stance', {})
    multi_stance = len(clips.get('equip', {})) > 1
    attack_specs = []       # (stance_or_None, state_name, generator_ref, evt)
    for kf, evt in zip(clips['attacks'], build_attack_events(clips)):
        st_name = f'Attack_{clip_state_name(kf)}'
        clip = _clip(st_name, kf, False,
                     _clip_triggers(st_name, 'returnToDefault'))
        mg = pf.add('hkbModifierGenerator')
        mg.param('variableBindingSet', 'null')
        mg.param('userData', 1)
        mg.param('name', f'{st_name}_MG')
        mg.param('modifier', attack_ml.ref)
        mg.param('generator', clip.ref)
        stance = stance_of.get(kf) if multi_stance else None
        if stance not in clips.get('equip', {}):
            stance = None
        attack_specs.append((stance, st_name, mg.ref, evt))

    if multi_stance and any(sp[0] for sp in attack_specs):
        # One sub-machine per stance holding that stance's attacks, wrapped in
        # a selector whose ACTIVE state is bound to iRightHandType.  The
        # engine writes that variable when it equips; the selector therefore
        # exposes only the matching stance's attacks.  Hand types are the
        # Skyrim WEAP DNAM 'Animation Type' enum (wbWeaponAnimTypeEnum:
        # 0 HandToHandMelee, 1-4 one-handed, 5 TwoHandSword, 6 TwoHandAxe,
        # 7 Bow, 8 Staff), so binding to it indexes stances directly.
        by_stance = {}
        for stance, st_name, gen_ref, evt in attack_specs:
            by_stance.setdefault(stance, []).append((st_name, gen_ref, evt))

        # hand type -> the stance that owns it, so the selector's stateId IS
        # the hand type the engine wrote (no remap table at runtime).
        stance_by_type = {}
        for stance in clips.get('equip', {}):
            for t in EQUIP_STANCES[stance][2]:
                stance_by_type[t] = stance

        # EVERY hand type the engine can write must resolve to a state, or the
        # actor has no attack at all while holding that weapon class (a
        # selector whose bound startStateId names no state selects nothing).
        # The creature only has clips for the stances it shipped, so any
        # uncovered type falls back to its nearest armed stance, else H2H --
        # a converted actor can be handed a weapon class Oblivion never
        # animated for it, and playing the wrong swing beats standing inert.
        _FALLBACK_ORDER = ('OneH', 'TwoH', 'Staff', 'Bow', 'H2H')
        have = [st for st in _FALLBACK_ORDER if st in clips.get('equip', {})]
        for t in range(10):
            if t not in stance_by_type and have:
                stance_by_type[t] = have[0]

        sel_states = []
        for hand_type in sorted(stance_by_type):
            stance = stance_by_type[hand_type]
            entries = by_stance.get(stance) or by_stance.get(None) or []
            if not entries:
                continue
            inner = []
            trans = []
            for i, (st_name, gen_ref, evt) in enumerate(entries):
                inner.append(_state(i, f'{st_name}State', gen_ref,
                                    exit_events=['attackStop'],
                                    transitions=[(eid['returnToDefault'],
                                                  0, _F_LOCAL)]))
                trans.append((eid[evt], i, _F_WILD))
            # unstanced attacks stay reachable in every stance
            for st_name, gen_ref, evt in by_stance.get(None, []):
                if any(x[0] == st_name for x in entries):
                    continue
                idx = len(inner)
                inner.append(_state(idx, f'{st_name}State', gen_ref,
                                    exit_events=['attackStop'],
                                    transitions=[(eid['returnToDefault'],
                                                  0, _F_LOCAL)]))
                trans.append((eid[evt], idx, _F_WILD))
            sub = _make_sm(f'Attack_{stance}_SM', inner, start_id=0,
                           wildcard_ref=_trans_array(trans).ref)
            sel_states.append(_state(hand_type, f'Attack_{stance}_State',
                                     sub.ref))
        if sel_states:
            sel_bind = _binding_set([('startStateId', 'iRightHandType')])
            # start in the lowest hand type present (0 = unarmed whenever
            # the creature has an H2H stance), matching iRightHandType's own
            # init value so the graph is consistent before the first equip.
            selector = _make_sm('AttackStanceSelector', sel_states,
                                start_id=min(stance_by_type),
                                binding_ref=sel_bind.ref)
            root_states_inner.append(_state(
                next_id, 'AttackStanceState', selector.ref,
                transitions=[(eid['returnToDefault'], 0, _F_LOCAL)]))
            for _stance, _st_name, _gen, evt in attack_specs:
                default_trans.append((eid[evt], next_id, _F_LOCAL))
            next_id += 1
    else:
        for stance, st_name, gen_ref, evt in attack_specs:
            root_states_inner.append(_state(
                next_id, f'{st_name}State', gen_ref,
                exit_events=['attackStop']))
            default_trans.append((eid[evt], next_id, _F_LOCAL))
            next_id += 1

    # Equip / unequip states. The engine sends weaponDraw when it wants the
    # actor armed; the expression modifier below translates that into the
    # per-class equipStart_* event matching the engine-set iRightHandType, and
    # the clip's END trigger replies weaponDraw so the combat controller knows
    # the actor is ready. Sheathing is the mirror image.
    equip_dispatch = []
    for stance, (eq, uneq) in sorted(clips.get('equip', {}).items()):
        hand_types = EQUIP_STANCES[stance][2]
        for kind, kf, reply in (('equip', eq, 'weaponDraw'),
                                ('unequip', uneq, 'weaponSheathe')):
            if kf is None:
                continue
            st_name = f'{kind.capitalize()}_{stance}'
            evt = f'{kind}Start_{stance}'
            clip = _clip(st_name, kf, False, _clip_triggers(st_name, reply))
            root_states_inner.append(_state(
                next_id, f'{st_name}State', clip.ref,
                transitions=[(eid['returnToDefault'], 0, _F_LOCAL)]))
            root_wilds.append((eid[evt], next_id, _F_WILD))
            next_id += 1
            equip_dispatch.append((kind, evt, hand_types))

    # ---- spellcasting: the vanilla FireForget chain (see CAST_MODES) ----
    # One In/Loop/Out sub-machine, entered by the ENGINE-sent
    # Spell_FireForget_LH/RH events (vanilla keys the transition into
    # FireForgetState on exactly these — never on BeginCast*, which is the
    # graph's outbound message). The In clip's Magic_Pre_Out end trigger
    # chains into the Loop; the engine's Spell_Release moves to the Out,
    # whose MLh_SpellFire_Event trigger at the authored release moment is
    # what actually fires the spell; its Spell_Stop end trigger exits.
    if cast_defs:
        cast_stems = cast_anim_stems(clips)
        # Release moment inside the Out slice (hit_times carries it under
        # the Out state's name — see generate_creature_project; 0.233s is
        # vanilla's own Mag_FF_RH_Out release offset as the fallback).
        release_t = (hit_times.get('Mag_FF_Out') or [0.233334])[0]
        cast_clip_gens = []
        for st_name, kf, phase, _stem in cast_defs:
            looping = (phase == 'Loop')
            items = []
            if phase == 'In':
                items.append(_TRIGGER_TMPL.format(
                    time=0.0, event_id=eid['Magic_Pre_Out'], rel='true'))
            elif phase == 'Out':
                # THE RELEASE — both hand events, because vanilla's own data
                # answers a right-hand cast with the LEFT event (both
                # atronach Out clips fire MLh_SpellFire_Event) and the extra
                # event is inert when that hand has no cast in flight.
                items.append(_TRIGGER_TMPL.format(
                    time=release_t, event_id=eid['MLh_SpellFire_Event'],
                    rel='false'))
                items.append(_TRIGGER_TMPL.format(
                    time=release_t, event_id=eid['MRh_SpellFire_Event'],
                    rel='false'))
                items.append(_TRIGGER_TMPL.format(
                    time=0.0, event_id=eid['Spell_Stop'], rel='true'))
            trig = 'null'
            if items:
                ta = pf.add('hkbClipTriggerArray')
                ta.param_raw('triggers', '\n'.join(items),
                             numelements=len(items))
                trig = ta.ref
            cast_clip_gens.append(_clip(st_name, kf, looping, trig,
                                        anim=cast_stems.get(st_name)))
        in_clip, loop_clip, out_clip = cast_clip_gens
        # In -> Loop on the In clip's own end trigger; the engine may
        # commit early, so Spell_Release must work from the WHOLE chain
        # (vanilla scopes it as a wildcard of the FF sub-machine).
        ff_states = [
            _state(0, 'Mag_FF_InState', in_clip.ref,
                   transitions=[(eid['Magic_Pre_Out'], 1, _F_LOCAL)]),
            _state(1, 'Mag_FF_LoopState', loop_clip.ref),
            _state(2, 'Mag_FF_OutState', out_clip.ref),
        ]
        ff_wild = _trans_array([
            (eid['Spell_Release'], 2, _F_WILD),
            (eid['Spell_Ready'], 0,
             'FLAG_IS_LOCAL_WILDCARD|'
             'FLAG_ALLOW_SELF_TRANSITION_BY_TRANSITION_FROM_ANY_STATE|'
             'FLAG_DISABLE_CONDITION'),
        ])
        ff_sm = _make_sm('Mag_FF_Behavior', ff_states, start_id=0,
                         wildcard_ref=ff_wild.ref)
        # IsCasting is held true for the whole chain via one IsActive
        # modifier over the sub-machine (vanilla BSIsActiveModifier_Spells);
        # the engine's `!IsCasting` guard blocks a second overlapping cast.
        #
        # bAnimationDriven is held true alongside it: while set, the engine
        # takes the actor's motion from the clip's root motion instead of
        # the commanded AI velocity, and the cast slices carry no root
        # motion at all — so the actor stands planted for the whole
        # In/Loop/Out chain and moves again the moment it exits.  Without
        # this the combat AI keeps commanding ground movement under the
        # full-body cast clip and the actor slides on planted feet (scamp,
        # reported in game 2026-08-26; the slide became visible when the
        # strafe MOVT columns went live in the strafe-locomotion pass —
        # before that, commanded circling multiplied into a 0 max speed).
        #
        # This is vanilla's own mechanism for a walking creature caster:
        # chaurusbehavior's Casting_SpitAttack_MG wraps its cast clip in
        # `bAnimationDriven_IsActive` (BSIsActiveModifier, bIsActive0 →
        # bAnimationDriven — pointer-traced, not name-guessed), and the
        # chaurus declares ONLY ChaurusDefault_MT.  The vanilla
        # slaughterfish does the same for stagger/recoil as an expression
        # (`bAnimationDriven = IsStaggering || IsRecoiling`).  An all-zero
        # `Rooted` MOVT switched by `iState = cond((IsCasting == 1), ...)`
        # at the root — the draugr-blocking shape — was tried 2026-08-26
        # and broke casting entirely in game; do not retry it.
        cast_iso = pf.add('BSIsActiveModifier')
        #
        # bAllowRotation is held too: an animation-driven actor cannot turn
        # by itself, and the AI faces its target before it will release a
        # cast, so a pinned caster that cannot rotate waits on a player who
        # keeps circling (Oblivion scamps turn while casting).  Vanilla
        # keeps rotation on for ranged actions (falmerbehavior's
        # bAllowRotation guard names hand type 7 = ranged explicitly), and
        # our own attack modifier already holds it the same way.
        cast_iso.param('variableBindingSet',
                       _binding_set([('bIsActive0', 'IsCasting'),
                                     ('bIsActive1', 'bAnimationDriven'),
                                     ('bIsActive2', 'bAllowRotation')]).ref)
        cast_iso.param('userData', 1)
        cast_iso.param('name', 'BSIsActiveModifier_Spells')
        cast_iso.param('enable', True)
        for i in range(5):
            cast_iso.param(f'bIsActive{i}', False)
            cast_iso.param(f'bInvertActive{i}', False)
        cast_ml = pf.add('hkbModifierList')
        cast_ml.param('variableBindingSet', 'null')
        cast_ml.param('userData', 1)
        cast_ml.param('name', 'Spells_ModifierList')
        cast_ml.param('enable', True)
        cast_ml.param_array('modifiers', [cast_iso.ref])
        cast_mg = pf.add('hkbModifierGenerator')
        cast_mg.param('variableBindingSet', 'null')
        cast_mg.param('userData', 1)
        cast_mg.param('name', 'FF_MG')
        cast_mg.param('modifier', cast_ml.ref)
        cast_mg.param('generator', ff_sm.ref)
        ff_id = next_id
        next_id += 1
        root_states_inner.append(_state(
            ff_id, 'FireForgetState', cast_mg.ref,
            transitions=[(eid['Spell_Stop'], 0, _F_LOCAL),
                         (eid['Spell_Interrupt'], 0, _F_LOCAL),
                         (eid['InterruptCast'], 0, _F_LOCAL)]))
        # THE ENTRY PATH: the engine sends the cast-type event after hearing
        # our BeginCast* (vanilla CombatIdleState keys on these verbatim).
        # Concentration spells get the same gesture — the engine drives
        # their release itself, and the stray SpellFire event is inert.
        for evt in ('Spell_FireForget_LH', 'Spell_FireForget_RH',
                    'Spell_Concentration_LH'):
            root_wilds.append((eid[evt], ff_id, _F_WILD))
        # Magic_Equip = "snap to combat idle" in vanilla; our combat idle
        # lives inside DefaultState.
        root_wilds.append((eid['Magic_Equip'], 0, _F_WILD))

    # ---- blocking (engine blockStart/blockStop; see BLOCK_CLIPS) ----
    # BlockState loops the guard with IsBlocking held true (the engine reads
    # it — draugrbehavior binds the same variable in its block states);
    # blockHitStart plays the flinch and returns to the guard.
    blk = clips.get('block', {})
    if blk.get('idle'):
        block_iso = pf.add('BSIsActiveModifier')
        block_iso.param('variableBindingSet',
                        _binding_set([('bIsActive0', 'IsBlocking')]).ref)
        block_iso.param('userData', 1)
        block_iso.param('name', 'BSIsActiveModifier_IsBlocking')
        block_iso.param('enable', True)
        for i in range(5):
            block_iso.param(f'bIsActive{i}', False)
            block_iso.param(f'bInvertActive{i}', False)
        block_ml = pf.add('hkbModifierList')
        block_ml.param('variableBindingSet', 'null')
        block_ml.param('userData', 1)
        block_ml.param('name', 'Block_ModifierList')
        block_ml.param('enable', True)
        block_ml.param_array('modifiers', [block_iso.ref])

        def _block_mg(nm, gen_ref):
            mg = pf.add('hkbModifierGenerator')
            mg.param('variableBindingSet', 'null')
            mg.param('userData', 1)
            mg.param('name', nm)
            mg.param('modifier', block_ml.ref)
            mg.param('generator', gen_ref)
            return mg

        block_id = next_id
        next_id += 1
        hit_id = None
        if blk.get('hit'):
            hit_id = next_id
            next_id += 1
        block_trans = [(eid['blockStop'], 0, _F_LOCAL)]
        if hit_id is not None:
            block_trans.append((eid['blockHitStart'], hit_id, _F_LOCAL))
        root_states_inner.append(_state(
            block_id, 'BlockState',
            _block_mg('Block_MG',
                      _clip('Block', blk['idle'], True).ref).ref,
            transitions=block_trans))
        root_wilds.append((eid['blockStart'], block_id, _F_WILD))
        if hit_id is not None:
            # the flinch fires its own blockHitStop at clip end, so the
            # guard resumes even if the engine never sends the stop (no
            # _clip_triggers here: an authored 'Hit' key on a flinch must
            # NOT become a damage HitFrame)
            bh_ta = pf.add('hkbClipTriggerArray')
            bh_ta.param_raw('triggers', _TRIGGER_TMPL.format(
                time=0.0, event_id=eid['blockHitStop'], rel='true'),
                numelements=1)
            hit_clip = _clip('BlockHit', blk['hit'], False, bh_ta.ref)
            root_states_inner.append(_state(
                hit_id, 'BlockHitState',
                _block_mg('BlockHit_MG', hit_clip.ref).ref,
                transitions=[(eid['blockHitStop'], block_id, _F_LOCAL),
                             (eid['blockStop'], 0, _F_LOCAL)]))
            root_wilds.append((eid['blockHitStart'], hit_id, _F_WILD))

    # Vocal idle states (CSDT Idle/Aware slots). Single-play — the sound
    # annotation lives in the state's OWN animation file, so it fires once
    # per entry, and entry is paced by the engine's idle system through the
    # ActionIdle / ActionIdleWarn IDLE records (tes5_import/creature_idles),
    # exactly like vanilla WolfIdleHowl / WolfIdleWarn. Embedding the sound
    # in the looping Idle/CombatStance clips instead made it fire every
    # cycle, in life and in the ragdoll wrapper states after death.
    #
    # IdleStop is LOCAL to these idle states, never a root wildcard: vanilla
    # routes idleStop only out of its idle states (atronach CombatIdleSpecial
    # -> CombatIdle, MT_Idle specials -> MT_Idle; sabrecat/draugr likewise).
    # A cast is itself an IDLE-manager action (ActionLeftAttack tree), and
    # the engine cancels idles with ActionIdleStop, so a root-level
    # IdleStop -> DefaultState wildcard killed every FireForget/Attack state
    # the moment the AI wanted to move: the actor snapped back to Default
    # while the engine stayed in its casting state waiting for a SpellFire /
    # Spell_Stop that could no longer come (the 2026-08-23 "IsCasting=1,
    # graph in DefaultState, never casts" readback).
    for st_name, evt, stem in (vocal_states or []):
        clip = _clip(st_name, clips['idle'], False,
                     _clip_triggers(st_name, 'returnToDefault'), anim=stem)
        root_states_inner.append(_state(
            next_id, f'{st_name}State', clip.ref,
            transitions=[(eid['IdleStop'], 0, _F_LOCAL)]))
        root_wilds.append((eid[evt], next_id, _F_WILD))
        next_id += 1

    equip_eem = None
    if equip_dispatch:
        # weaponDraw/weaponSheathe -> the class-specific enter event. Guarded on
        # iRightHandType so a bow draw plays bowequip and a mace draw plays
        # onehandequip; the H2H entry (hand type 0) doubles as the fallback.
        exprs = []
        for kind, evt, hand_types in equip_dispatch:
            src = 'weaponDraw' if kind == 'equip' else 'weaponSheathe'
            cond = ' || '.join(f'(iRightHandType == {t})' for t in hand_types)
            exprs.append(f'{evt} if (({src}) && ({cond}))')
        arr = pf.add('hkbExpressionDataArray')
        arr.param_raw('expressionsData', '\n'.join(
            '<hkobject>\n'
            f'\t<hkparam name="expression">{e}</hkparam>\n'
            '\t<hkparam name="assignmentVariableIndex">-1</hkparam>\n'
            '\t<hkparam name="assignmentEventIndex">-1</hkparam>\n'
            '\t<hkparam name="eventMode">EVENT_MODE_SEND_ON_FALSE_TO_TRUE'
            '</hkparam>\n'
            '</hkobject>' for e in exprs), numelements=len(exprs))
        eem = pf.add('hkbEvaluateExpressionModifier')
        eem.param('variableBindingSet', 'null')
        eem.param('userData', 2)
        eem.param('name', 'EquipDispatch_EEM')
        eem.param('enable', True)
        eem.param('expressions', arr.ref)
        equip_eem = eem

    # ---- cast gating (vanilla BeginCast_EEM, VERBATIM and nothing else) --
    # These two expressions are copied character-for-character from
    # atronachflamebehavior. BeginCast* is the graph's message TO the
    # engine: the engine hears it and replies with Spell_FireForget_LH (the
    # state-entry event above). Expressions can only read VARIABLES — the
    # previous attempt tested event names in conditions, which never fire.
    cast_eem = None
    if cast_defs:
        exprs = [
            'BeginCastLeft if (bWantCastLeft && bMLh_Ready && !IsCasting)',
            'BeginCastRight if (bWantCastRight && bMRh_Ready && !IsCasting)',
        ]
        # EVENT_MODE_SEND_ON_TRUE, not vanilla's SEND_ON_FALSE_TO_TRUE.
        # The engine binds BeginCastLeft -> LeftHandSpellCastHandler (read
        # out of the live per-actor dispatcher map, 2026-08-26), whose whole
        # job is: if this hand's ActorMagicCaster is in state 1 ("want-cast
        # issued, waiting for the animation"), advance it to state 2 and
        # PerformAction(ActionLeftAttack) -> the IDLE tree -> the
        # Spell_FireForget_LH that enters our cast chain.  It is a no-op in
        # every other state.  A live scamp sat for minutes with
        # bWantCastLeft=1, bMLh_Ready=1, IsCasting=0 and the caster parked
        # in state 1: the one false->true edge had come and gone with
        # nothing to show for it, and the engine never rewrites the flag
        # while it waits, so an edge-triggered expression can never fire
        # again ("the scamp only casts when the graph is hit just right").
        # Raising the event every frame the condition holds makes the
        # handshake un-missable; the moment the cast starts IsCasting=1
        # turns it off, and the handler ignores it in any other state.
        arr = pf.add('hkbExpressionDataArray')
        arr.param_raw('expressionsData', '\n'.join(
            '<hkobject>\n'
            f'\t<hkparam name="expression">{e}</hkparam>\n'
            '\t<hkparam name="assignmentVariableIndex">-1</hkparam>\n'
            '\t<hkparam name="assignmentEventIndex">-1</hkparam>\n'
            '\t<hkparam name="eventMode">EVENT_MODE_SEND_ON_TRUE'
            '</hkparam>\n'
            '</hkobject>' for e in exprs), numelements=len(exprs))
        eem = pf.add('hkbEvaluateExpressionModifier')
        eem.param('variableBindingSet', 'null')
        eem.param('userData', 2)
        eem.param('name', 'BeginCast_EEM')
        eem.param('enable', True)
        eem.param('expressions', arr.ref)
        cast_eem = eem

    # ---- swim movement-type switch (vanilla quadruped verbatim shape) ----
    # While the engine-written isSwimming is set, iState points at the swim
    # MOVT, giving the actor its water speeds; on land it points back at
    # Default. Without this the engine keeps the land movement type in
    # water. (`iState = cond((isSwimming ==1), iState_BearSwimDefault,
    # iState_BearDefault)` is the vanilla original.)
    #
    # iState is for SWIM ONLY.  Wrapping this expression in
    # `cond((IsCasting == 1), iState_<base>Rooted, ...)` onto an all-zero
    # MOVT — to pin a caster — was tried 2026-08-26 and BROKE casting
    # entirely in game.  The working pin is bAnimationDriven in the cast
    # chain's own modifier list (see BSIsActiveModifier_Spells above),
    # which is chaurusbehavior verbatim.
    swim_eem = None
    if has_swim_mt:
        default_mt, swim_mt = None, None
        for mt in movement_types:
            if mt.endswith('Swim'):
                swim_mt = f'iState_{mt}'
            elif mt.endswith('Default'):
                default_mt = f'iState_{mt}'
