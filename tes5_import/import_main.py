    reset_sunless_climates()
    if ctx and getattr(ctx, 'master_export', None):
        for mrec in ctx.master_export.values():
            if (mrec.get('Signature') or '') == 'CLMT':
                record_sunless_climate(mrec)
    for rec in by_type.get('CLMT', []):
        record_sunless_climate(rec)

    # Serial on purpose: this whole phase is ~1.5s of GIL-bound Python, so a
    # thread pool adds no speed — but it DID make the output nondeterministic:
    # converters that emit companion records (ARMA, aimed-MGEF clones, …) added
    # them in thread-completion order, so record order shuffled between runs. A
    # plain loop keeps the ESM byte-reproducible. (The genuinely heavy
    # conversion work — text parse, LAND, navmeshes — runs in pools elsewhere.)
    for sig, target_sig, rec in work_items:
        converter = IMPORT_DISPATCH[sig]
        try:
            src_fid = (rec.get('FormID') or '').upper()

            # OVERRIDE: the master's converted record with only the author's
            # changes substituted (see overrides.py). Nothing is re-derived, so
            # nothing can drift: this is what stops 1821 NPC_ races being
            # rewritten to vanilla Skyrim ones when the author changed none.
            # A 'reconvert' result (authored effect-list change) falls through
            # to the normal path — its FormID still lands on the master's.
            ov = ctx.build(rec, sig) if ctx else None
            if ov is not None and ov.status != 'reconvert':
                if ov.record_bytes:
                    # Same authority rule as below: the packed record's own
                    # signature picks the group (a master's STAT may have been
                    # retyped to MSTT, a BOOK to SCRL).
                    writer.add_record(
                        ov.record_bytes[:4].decode('ascii', 'replace'),
                        ov.record_bytes)
                    converted += 1
                continue

            # NEW record: the normal conversion path, unchanged.
            with writer.converting(src_fid, get_formid(rec, 'FormID')):
                if sig in _WRITER_TYPES:
                    record_bytes = converter(rec, writer=writer)
                else:
                    record_bytes = converter(rec)
            # A converter returning None chose to emit nothing for this
            # record (convert_REGN skips regions with no weather list —
            # their object/grass/sound data drives TES4-side generators with
            # no equivalent here).
            if not record_bytes:
                continue
            # A converter may retarget PER RECORD, not just per signature:
            # a TES4 BOOK carrying an enchantment is a scroll, and Skyrim's
            # BOOK has no field for an object effect, so convert_BOOK emits a
            # SCRL for those and a BOOK for the rest.  The packed record's own
            # 4-byte signature is the authority on which group it belongs in —
            # filing a SCRL under the BOOK group makes the engine read it as a
            # BOOK and the scroll silently reverts to unusable paper.
            writer.add_record(record_bytes[:4].decode('ascii', 'replace'),
                              record_bytes)
            converted += 1
        except Exception as e:
            edid = get_str(rec, 'EditorID', '?')
            print(f"  ERROR converting {sig} '{edid}': {e}")
            errors += 1
    _phase_done(f'phase 1 simple records ({len(work_items)})')

